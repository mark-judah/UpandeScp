#!/usr/bin/env node
/**
 * One icon set (item 9b): build every icon target from one source.
 *
 * Source:  upande_scp/shared/icons/<category>/<key>.svg  (24×24, currentColor)
 * Targets (all committed):
 *   a. upande_scp/shared/icons/manifest.json         — SCP web (SharedIcon, MarkerDefs, WeatherGlyph)
 *   b. upande_scp/public/icons/scp-icons.svg         — Frappe desk sprite (app_include_icons)
 *   c. <livestock>/upande_livestock/public/icons/<name>.svg — from the `notice` category
 *   d. <scout rn>/src/icons/sharedIcons.ts           — Scout RN (StageIcon via SvgXml)
 *
 * Plain Node, no dependencies.
 *   node scripts/build_icons.mjs           write every target
 *   node scripts/build_icons.mjs --check   exit 1 when any target is stale
 *
 * The sibling repos (c, d) are optional: when their directory is absent the
 * target is skipped with a note. Override with LIVESTOCK_DIR / SCOUT_RN_DIR.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "upande_scp", "shared", "icons");
const CATEGORIES = ["stage", "weather", "notice", "brand"];
const DEFAULT_STAGE_KEY = "circle";

const LIVESTOCK_DIR =
  process.env.LIVESTOCK_DIR || path.resolve(ROOT, "..", "upande_livestock");
const SCOUT_RN_DIR =
  process.env.SCOUT_RN_DIR ||
  path.resolve(ROOT, "..", "..", "..", "reactnative", "Upande-Scout", "upande_scout_rn");

const BANNER = "Generated by upande_scp/scripts/build_icons.mjs — do not edit.";

const SVG_RE = /^\s*(?:<!--[\s\S]*?-->\s*)*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/;
const ATTR_RE = /([\w:-]+)="([^"]*)"/g;

function parseSvg(file) {
  const text = fs.readFileSync(file, "utf8");
  const m = SVG_RE.exec(text);
  if (!m) throw new Error(`${file}: not a single <svg> root`);
  const attrs = {};
  for (const [, k, v] of m[1].matchAll(ATTR_RE)) attrs[k] = v;
  const { xmlns: _x, viewBox, ...rest } = attrs;
  if (viewBox !== "0 0 24 24") throw new Error(`${file}: viewBox must be "0 0 24 24", got "${viewBox}"`);
  return { text, viewBox, attrs: rest, body: m[2].trim() };
}

function loadIcons() {
  const icons = {};
  for (const category of CATEGORIES) {
    const dir = path.join(SRC, category);
    const files = fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort();
    for (const f of files) {
      const key = f.slice(0, -4);
      if (!/^[a-z0-9-]+$/.test(key)) throw new Error(`${category}/${f}: key must be [a-z0-9-]`);
      icons[`${category}/${key}`] = { category, key, ...parseSvg(path.join(dir, f)) };
    }
  }
  if (!icons[`stage/${DEFAULT_STAGE_KEY}`]) throw new Error(`missing stage/${DEFAULT_STAGE_KEY}`);
  return icons;
}

const attrString = (attrs) =>
  Object.entries(attrs).map(([k, v]) => ` ${k}="${v}"`).join("");

/** Standalone, self-contained SVG for one icon (RN SvgXml, desk previews). */
const standalone = (i) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${i.viewBox}"${attrString(i.attrs)}>${i.body}</svg>`;

function buildManifest(icons) {
  const out = { _generated: BANNER, defaultStageKey: DEFAULT_STAGE_KEY, icons: {} };
  for (const [name, i] of Object.entries(icons)) {
    out.icons[name] = { category: i.category, key: i.key, viewBox: i.viewBox, attrs: i.attrs, body: i.body };
  }
  return JSON.stringify(out, null, 2) + "\n";
}

function buildSprite(icons) {
  // Frappe's `frappe.utils.icon(name)` renders `<use href="#icon-<name>">`, so
  // the DOM id carries the `icon-` prefix: frappe.utils.icon("scp-stage-star").
  const symbols = Object.values(icons).map(
    (i) =>
      `<symbol id="icon-scp-${i.category}-${i.key}" viewBox="${i.viewBox}"${attrString(i.attrs)}>${i.body}</symbol>`,
  );
  return (
    `<!-- ${BANNER} Source: upande_scp/shared/icons. Use: frappe.utils.icon("scp-<category>-<key>") -->\n` +
    `<svg id="scp-symbols" aria-hidden="true" style="display: none;" xmlns="http://www.w3.org/2000/svg">\n` +
    symbols.join("\n") +
    `\n</svg>\n`
  );
}

function buildLivestock(icons) {
  const files = {};
  for (const i of Object.values(icons)) {
    if (i.category !== "notice") continue;
    files[`${i.key}.svg`] =
      `<!-- ${BANNER} Source: upande_scp/shared/icons/notice/${i.key}.svg -->\n` + i.text.trim() + "\n";
  }
  return files;
}

function buildRn(icons) {
  const lines = Object.entries(icons).map(
    ([name, i]) => `  ${JSON.stringify(name)}:\n    ${JSON.stringify(standalone(i))},`,
  );
  return (
    `// ${BANNER}\n` +
    `// Source: upande_scp/shared/icons (the SCP repo). Rerun the generator there.\n\n` +
    `export const DEFAULT_STAGE_KEY = ${JSON.stringify(DEFAULT_STAGE_KEY)};\n\n` +
    `/** "<category>/<key>" → standalone SVG XML (currentColor). */\n` +
    `export const SHARED_ICONS: Record<string, string> = {\n${lines.join("\n")}\n};\n`
  );
}

function targets(icons) {
  const t = [
    [path.join(SRC, "manifest.json"), buildManifest(icons)],
    [path.join(ROOT, "upande_scp", "public", "icons", "scp-icons.svg"), buildSprite(icons)],
  ];
  const skipped = [];
  const lsDir = path.join(LIVESTOCK_DIR, "upande_livestock", "public", "icons");
  if (fs.existsSync(path.join(LIVESTOCK_DIR, "upande_livestock"))) {
    for (const [f, c] of Object.entries(buildLivestock(icons))) t.push([path.join(lsDir, f), c]);
  } else skipped.push(`livestock (${LIVESTOCK_DIR})`);
  if (fs.existsSync(path.join(SCOUT_RN_DIR, "package.json"))) {
    t.push([path.join(SCOUT_RN_DIR, "src", "icons", "sharedIcons.ts"), buildRn(icons)]);
  } else skipped.push(`scout rn (${SCOUT_RN_DIR})`);
  return { t, skipped };
}

function main() {
  const check = process.argv.includes("--check");
  const icons = loadIcons();
  const { t, skipped } = targets(icons);
  for (const s of skipped) console.warn(`skip: ${s} not found`);
  const stale = [];
  for (const [file, content] of t) {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (cur === content) continue;
    if (check) stale.push(file);
    else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
      console.log(`wrote ${path.relative(process.cwd(), file)}`);
    }
  }
  if (check) {
    if (stale.length) {
      console.error(`stale icon outputs (run node scripts/build_icons.mjs):\n  ${stale.join("\n  ")}`);
      process.exit(1);
    }
    console.log(`icons up to date (${Object.keys(icons).length} icons, ${t.length} files)`);
  }
}

main();
